-- Q3 WAQTD EMPNO AND NAME OF THE EMPLOYEES HIRED AFTER 1981 AND BEFORE 1987  AND EARNING MORE THAN 1500 OR WORKING IN DEPT 10.
    SELECT EMPNO,ENAME
    FROM EMP
    WHERE (HIREDATE BETWEEN '1-JAN-1982' AND '31-DEC-1987' AND (SAL > 1500)) OR DEPTNO=10; 
-- Q4 WAQTD NAME AND SALARY OF THE EMPLOYEES EARNING BETWEEN 1500 AND 3000 
-- AND NOT WORKING AS CLERK OR WORKING IN DEPT 30.
      SELECT ENAME,SAL
      FROM EMP
      WHERE (SAL BETWEEN 1500 AND 3000) AND (JOB!='CLERK') OR DEPTNO=30; 

-- Q5 WAQTD EMPNO, NAME AND DEPTNO OF THE EMPLOYEES WORKING IN DEPT 10 
-- OR WORKING IN DEPT 20 AND EARNING MORE THAN 2000 AND NOT WORKING AS MANAGER.
    SELECT EMPNO,ENAME,DEPTNO
    FROM EMP
    WHERE DEPTNO=10 OR (DEPTNO=20 AND SAL> 2000 AND JOB!='MANAGER');
      

-- Q6 WAQTD NAME AND SALARY OF THE EMPLOYEES WORKING AS CLERK 
-- OR WORKING AS SALESMAN AND EARNING MORE THAN 1200 AND WORKING IN DEPT 30.
SELECT ENAME,SAL
FROM EMP
WHERE (JOB='CLERK' OR JOB='SALESMAN' )AND SAL>1200 AND DEPTNO IN(30));

-- Q7 WAQTD EMPNO, NAME AND SALARY OF THE EMPLOYEES EARNING MORE THAN 1000 
-- AND WORKING UNDER MANAGER 7698 OR WORKING UNDER MANAGER 7839 
-- AND WORKING IN DEPT 20.
   SELECT EMPNO,ENAME,SAL
   FROM EMP
   WHERE (SAL>1000 AND MGR=7698) OR (MGR=7839 AND DEPTNO=20);
 

-- Q8 WAQTD NAME AND ANNUAL SALARY OF THE EMPLOYEES WHOSE ANNUAL SALARY 
-- IS GREATER THAN 30000 AND WORKING IN DEPT 10 OR WORKING IN DEPT 20 
-- AND NOT WORKING AS CLERK.
   SELECT ENAME,SAL*12
   WHERE (SAL*12 > 3000) AND (DEPTNO=10 OR (DEPTNO=20 AND JOB!='CLERK'));



-- Q9 WAQTD EMPNO AND NAME OF THE EMPLOYEES WHO ARE NOT WORKING AS MANAGER 
-- AND NOT WORKING AS ANALYST AND EARNING MORE THAN 1000 OR WORKING IN DEPT 30.
   SELECT EMPNO,ENAME
   FROM EMP
   WHERE (JOB!='MANAGER' AND JOB!='ANALYST' AND  SAL>1000) OR DEPTNO=30;

-- Q10 WAQTD NAME AND ANNUAL SALARY OF THE EMPLOYEES WHOSE ANNUAL SALARY 
-- IS GREATER THAN 20000 AND NOT WORKING AS SALESMAN AND WORKING IN DEPT 20 
-- OR DEPT 30.
   SELECT ENAME,SAL*12 
   FROM EMP
   WHERE (SAL*12 >20000 AND JOB !='SALESMAN' AND DEPTNO=20) OR (DEPTNO=30);
               


