-- AND > OR (AND executes first)

-- 1. A AND B OR C      → (A AND B) OR C
-- 2. A OR B AND C      → A OR (B AND C)
-- 3. A AND (B OR C)    → same
-- 4. (A OR B) AND C    → same
-- 5. A AND B AND C     → no issue
-- 6. A OR B OR C       → no issue

-- SPECIAL:
-- NOT (A OR B)         → NOT A AND NOT B
-- NOT (A AND B)        → NOT A OR NOT B

-- COMMON PATTERNS:
-- CLERK OR SALESMAN AND cond
-- → (JOB='CLERK' OR JOB='SALESMAN') AND cond

-- DEPT 10 OR DEPT 20 AND cond
-- → DEPT=10 OR (DEPT=20 AND cond)

-- cond AND DEPT 10 OR DEPT 20
-- → (cond AND DEPT=10) OR DEPT=20

-- NOT MANAGER AND NOT ANALYST
-- → JOB NOT IN ('MANAGER','ANALYST')

